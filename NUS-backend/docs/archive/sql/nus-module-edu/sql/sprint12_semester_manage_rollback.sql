-- 说明：
-- - 本脚本为幂等脚本，可重复执行
-- - 若这些 config_key 在 sprint12 执行前已存在，执行本脚本会一并删除，请先备份
-- ============================================================

SET NAMES utf8mb4;

-- ============================================================
-- 1. 回滚菜单授权关系（先删关联，避免菜单删除冲突）
-- ============================================================

DELETE
FROM `system_role_menu`
WHERE `menu_id` IN (5119, 5120, 5121);

-- ============================================================
-- 2. 回滚菜单与按钮权限（先删子节点，再删父节点）
-- ============================================================

DELETE
FROM `system_menu`
WHERE `id` IN (5120, 5121);

DELETE
FROM `system_menu`
WHERE `id` = 5119;

-- ============================================================
-- 3. 回滚 infra_config 中的学期配置键
-- ============================================================

DELETE
FROM `infra_config`
WHERE `config_key` IN (
                       'edu.current.semester.name',
                       'edu.current.semester.start-date',
                       'edu.current.semester.end-date'
    );

